// refXdot is the reference's xdot output for
// digraph G { a -> b [label="x"]; a [shape=rect, color="#FF0000"] }.
const refXdot = `digraph G {
	graph [_draw_="c 9 -#fffffe00 C 7 -#ffffff P 4 0 0 0 124.8 54 124.8 54 0 ",
		bb="0,0,54,124.8",
		xdotversion=1.7
	];
	node [label="\N"];
	a	[_draw_="c 7 -#ff0000 p 4 54 124.8 0 124.8 0 88.8 54 88.8 ",
		_ldraw_="F 14 11 -Times-Roman c 7 -#000000 T 27 102.6 0 6.21 1 -a ",
		color="#FF0000",
		height=0.5,
		pos="27,106.8",
		shape=rect,
		width=0.75];
	b	[_draw_="c 7 -#000000 e 27 18 27 18 ",
		_ldraw_="F 14 11 -Times-Roman c 7 -#000000 T 27 13.8 0 7 1 -b ",
		height=0.5,
		pos="27,18",
		width=0.75];
	a -> b	[_draw_="c 7 -#000000 B 4 27 88.65 27 76.96 27 61.19 27 47.62 ",
		_hdraw_="S 5 -solid c 7 -#000000 C 7 -#000000 P 3 30.5 47.92 27 37.92 23.5 47.92 ",
		_ldraw_="F 14 11 -Times-Roman c 7 -#000000 T 30.5 58.2 0 7 1 -x ",
		label=x,
		lp="30.5,62.4",
		pos="e,27,36.41 27,88.651 27,76.958 27,61.192 27,47.618"];
}
`

func TestCompareDOT(t *testing.T) {
	for _, tt := range []struct {
		name string
		got  string
		ok   bool
	}{
		{"identical", refXdot, true},
		// Layout numbers in dot: a node 2 points away and a bb 3% larger
		// pass, and so does a curve of more segments.
		{"layout numbers", strings.NewReplacer(`pos="27,18"`, `pos="29,18"`, `bb="0,0,54,124.8"`, `bb="0,0,55.6,128.5"`,
			"B 4 27 88.65 27 76.96 27 61.19 27 47.62", "B 7 27 88.65 27 80 27 70 27 65 27 60 27 50 27 47.62").Replace(refXdot), true},
		// Missing drawing operation.
		{"missing arrowhead", strings.Replace(refXdot, "\t\t_hdraw_=\"S 5 -solid c 7 -#000000 C 7 -#000000 P 3 30.5 47.92 27 37.92 23.5 47.92 \",\n", "", 1), false},
		{"other color", strings.Replace(refXdot, "c 7 -#ff0000 p 4", "c 7 -#00ff00 p 4", 1), false},
		{"other text", strings.Replace(refXdot, "T 30.5 58.2 0 7 1 -x", "T 30.5 58.2 0 7 1 -y", 1), false},
		{"other font", strings.Replace(refXdot, "F 14 11 -Times-Roman c 7 -#000000 T 27 13.8", "F 14 9 -Helvetica c 7 -#000000 T 27 13.8", 1), false},
		{"other polygon", strings.Replace(refXdot, "P 3 30.5 47.92 27 37.92 23.5 47.92", "P 4 30.5 47.92 27 37.92 23.5 47.92 27 47", 1), false},
		{"missing attribute", strings.Replace(refXdot, "\t\tlp=\"30.5,62.4\",\n", "", 1), false},
		{"other value", strings.Replace(refXdot, "shape=rect", "shape=box", 1), false},
		{"missing node", strings.Replace(strings.Replace(refXdot, "a -> b", "a -> c", 1), "\tb\t[", "\tc\t[", 1), false},
		{"bb beyond 5%", strings.Replace(refXdot, `bb="0,0,54,124.8"`, `bb="0,0,54,140"`, 1), false},
	} {
		err := CompareDOT([]byte(refXdot), []byte(tt.got), SizeTolerance)
		if (err == nil) != tt.ok {
			t.Errorf("%s: %v", tt.name, err)
		}
	}
}

const refJSON = `{
  "name": "G",
  "directed": true,
  "strict": false,
  "_draw_": [
    {"op": "c", "grad": "none", "color": "#fffffe00"},
    {"op": "P", "points": [[0.000,0.000],[0.000,36.000],[54.000,36.000],[54.000,0.000]]}
  ],
  "bb": "0,0,54,36",
  "xdotversion": "1.7",
  "_subgraph_cnt": 0,
  "objects": [
    {
      "_gvid": 0,
      "name": "a",
      "_ldraw_": [
        {"op": "F", "size": 14.000, "face": "Times-Roman"},
        {"op": "T", "pt": [27.000,13.800], "align": "c", "width": 6.210, "text": "a"}
      ],
      "height": "0.5",
      "label": "\\N",
      "pos": "27,18",
      "width": "0.75"
    }
  ]
}
`

func TestCompareJSON(t *testing.T) {
	for _, tt := range []struct {
		name string
		got  string
		ok   bool
	}{
		{"identical", refJSON, true},
		{"layout numbers", strings.NewReplacer(`"pos": "27,18"`, `"pos": "28,19"`, `"pt": [27.000,13.800]`, `"pt": [28.000,14.800]`).Replace(refJSON), true},
		{"other text", strings.Replace(refJSON, `"text": "a"`, `"text": "b"`, 1), false},
		{"other id", strings.Replace(refJSON, `"_gvid": 0`, `"_gvid": 1`, 1), false},
		{"missing key", strings.Replace(refJSON, `"strict": false,`, ``, 1), false},
		{"bb beyond 5%", strings.Replace(refJSON, `"bb": "0,0,54,36"`, `"bb": "0,0,54,40"`, 1), false},
		{"two documents", refJSON + refJSON, false},
	} {
		err := CompareJSON([]byte(refJSON), []byte(tt.got), SizeTolerance)
		if (err == nil) != tt.ok {
			t.Errorf("%s: %v", tt.name, err)
		}
	}
}

func TestCompareInlineSVG(t *testing.T) {
	ref := "<!-- Generated by graphviz version 16.1.0 (20260904.0139)\n -->\n<!-- Title: G Pages: 1 -->\n" + okSVG
	got := "<!-- Generated by graphviz version 16.1.0 (gogv)\n -->\n<!-- Title: G Pages: 1 -->\n" + okSVG
	if err := CompareInlineSVG(fakeRasterizer{}, []byte(ref), []byte(got)); err != nil {
		t.Errorf("same drawing: %v", err)
	}
	prolog := `<?xml version="1.0" encoding="UTF-8" standalone="no"?>` + "\n" + got
	if err := CompareInlineSVG(fakeRasterizer{}, []byte(ref), []byte(prolog)); err == nil {
		t.Error("an XML declaration passes")
	}
}

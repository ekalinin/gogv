// GraphvizVersion is the version of Graphviz that gogv follows, which the
// SVG output names as its generator.
const GraphvizVersion = "16.1.0"

// svgPad is the margin the reference leaves around the drawing, in points.
const svgPad = 4

// SVG writes a laid-out graph as the reference's SVG output: a graph group
// whose transform puts the origin at the bottom left of the drawing, so that
// y coordinates are negative, then each node followed by the edges whose
// ends have both been written.
func SVG(res *layout.Result) []byte { return writeSVG(res, false) }

// SVGInline writes a laid-out graph as the reference's svg_inline output: the
// SVG output without the XML declaration, the document type and the
// namespace attributes, for inclusion in another document.
func SVGInline(res *layout.Result) []byte { return writeSVG(res, true) }

func writeSVG(res *layout.Result, inline bool) []byte {
	var b bytes.Buffer
	w, h := res.Width, res.Height
	g := res.Graph

	if !inline {
		b.WriteString(`<?xml version="1.0" encoding="UTF-8" standalone="no"?>` + "\n")
		b.WriteString(`<!DOCTYPE svg PUBLIC "-//W3C//DTD SVG 1.1//EN"` + "\n")
		b.WriteString(` "http://www.w3.org/Graphics/SVG/1.1/DTD/svg11.dtd">` + "\n")
	}
	b.WriteString("<!-- Generated by graphviz version " + GraphvizVersion + " (gogv)\n -->\n")
	if g.Name != "" {
		fmt.Fprintf(&b, "<!-- Title: %s Pages: 1 -->\n", xmlText(g.Name))
	} else {
		b.WriteString("<!-- Pages: 1 -->\n")
	}
	pw, ph := math.Round(w+2*svgPad), math.Round(h+2*svgPad)
	fmt.Fprintf(&b, "<svg width=\"%spt\" height=\"%spt\"\n", svgNumber(pw), svgNumber(ph))
	ns := ` xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink"`
	if inline {
		ns = ""
	}
	fmt.Fprintf(&b, " viewBox=\"0.00 0.00 %.2f %.2f\"%s>\n", pw, ph, ns)
	fmt.Fprintf(&b, "<g id=\"graph0\" class=\"graph\" transform=\"scale(1 1) rotate(0) translate(%s %s)\">\n", svgNumber(svgPad), svgNumber(h+svgPad))
	if g.Name != "" {
		fmt.Fprintf(&b, "<title>%s</title>\n", xmlText(g.Name))
	}
	fmt.Fprintf(&b, "<polygon fill=\"white\" stroke=\"none\" points=\"%s,%s %s,%s %s,%s %s,%s %s,%s\"/>\n",
		svgNumber(-svgPad), svgNumber(svgPad), svgNumber(-svgPad), svgNumber(-(h + svgPad)),
		svgNumber(w+svgPad), svgNumber(-(h + svgPad)), svgNumber(w+svgPad), svgNumber(svgPad),
		svgNumber(-svgPad), svgNumber(svgPad))
	if len(res.Label.Lines) > 0 {
		writeText(&b, res.Label, res.LabelPos)
	}
	for i := range res.Clusters {
		writeCluster(&b, &res.Clusters[i], i+1)
	}

	written := map[*layout.NodeResult]bool{}
	byNode := map[any]*layout.NodeResult{}
	for i := range res.Nodes {
		byNode[res.Nodes[i].Node] = &res.Nodes[i]
	}
	edgeDone := make([]bool, len(res.Edges))
	nodeID, edgeID := 0, 0
	for i := range res.Nodes {
		n := &res.Nodes[i]
		nodeID++
		writeNode(&b, n, nodeID)
		written[n] = true
		for j := range res.Edges {
			e := &res.Edges[j]
			if edgeDone[j] || !written[byNode[e.Edge.Tail]] || !written[byNode[e.Edge.Head]] {
				continue
			}
			edgeDone[j] = true
			if e.Invisible {
				continue
			}
			edgeID++
			writeEdge(&b, e, edgeID, g)
		}
	}
	b.WriteString("</g>\n</svg>\n")
	return b.Bytes()
}

func y(v float64) string { return svgNumber(-v) }

func svgColor(c string) string { return strings.ToLower(c) }

func writeNode(b *bytes.Buffer, n *layout.NodeResult, id int) {
	name := xmlText(n.Node.Name)
	fmt.Fprintf(b, "<!-- %s -->\n<g id=\"node%d\" class=\"node\">\n<title>%s</title>\n", name, id, name)
	color := svgColor(n.Color)
	switch n.Shape {
	case "ellipse", "oval", "circle":
		fmt.Fprintf(b, "<ellipse fill=\"none\" stroke=\"%s\" cx=\"%s\" cy=\"%s\" rx=\"%s\" ry=\"%s\"/>\n",
			color, svgNumber(n.X), y(n.Y), svgNumber(n.W/2), svgNumber(n.H/2))
	case "point":
		fmt.Fprintf(b, "<ellipse fill=\"%s\" stroke=\"%s\" cx=\"%s\" cy=\"%s\" rx=\"%s\" ry=\"%s\"/>\n",
			color, color, svgNumber(n.X), y(n.Y), svgNumber(n.W/2), svgNumber(n.H/2))
	case "plaintext":
	case "box", "rect", "rectangle":
		if !n.Rounded {
			writePolygon(b, n, color)
			break
		}
		var d strings.Builder
		for i, p := range layout.RoundedOutline(n.W, n.H) {
			switch i {
			case 0:
				d.WriteString("M")
			case 1:
				d.WriteString("C")
			default:
				d.WriteString(" ")
			}
			d.WriteString(svgNumber(n.X+p.X) + "," + y(n.Y+p.Y))
		}
		fmt.Fprintf(b, "<path fill=\"none\" stroke=\"%s\" d=\"%s\"/>\n", color, d.String())
	default:
		writePolygon(b, n, color)
	}
	if n.Shape != "point" {
		writeLabel(b, n.Label, layout.Point{X: n.X, Y: n.Y}, color)
	}
	if n.XLabel.Present() {
		writeLabel(b, n.XLabel, n.XLabelPos, color)
	}
	b.WriteString("</g>\n")
}

// writeCluster writes the box of a cluster, from its lower left corner
// upward and around, and its label.
func writeCluster(b *bytes.Buffer, c *layout.ClusterResult, id int) {
	fmt.Fprintf(b, "<g id=\"clust%d\" class=\"cluster\">\n<title>%s</title>\n", id, xmlText(c.Graph.Name))
	x0, y0, x1, y1 := svgNumber(c.X0), y(c.Y0), svgNumber(c.X1), y(c.Y1)
	fmt.Fprintf(b, "<polygon fill=\"none\" stroke=\"%s\" points=\"%s,%s %s,%s %s,%s %s,%s %s,%s\"/>\n",
		svgColor(c.Color), x0, y0, x0, y1, x1, y1, x1, y0, x0, y0)
	if c.Label.Present() {
		writeLabel(b, c.Label, c.LabelPos, svgColor(c.Color))
	}
	b.WriteString("</g>\n")
}

// writePolygon writes the outline of a polygonal node.
func writePolygon(b *bytes.Buffer, n *layout.NodeResult, color string) {
	var pts []string
	vs := layout.PolygonVertices(n.Shape, n.W, n.H)
	for _, v := range append(vs, vs[0]) {
		pts = append(pts, svgNumber(n.X+v.X)+","+y(n.Y+v.Y))
	}
	fmt.Fprintf(b, "<polygon fill=\"none\" stroke=\"%s\" points=\"%s\"/>\n", color, strings.Join(pts, " "))
}

// writeLabel writes a label centered on c: its lines, or its table as
// tableBoxes draws it, with pen the color of the object's outline.
func writeLabel(b *bytes.Buffer, t layout.Text, c layout.Point, pen string) {
	if t.Table == nil {
		writeText(b, t, c)
		return
	}
	for _, bx := range tableBoxes(t, c, pen) {
		fill, stroke, sw := bx.fill, bx.stroke, ""
		if bx.stroke == "" {
			stroke = "none"
		} else {
			fill = "none"
		}
		if bx.width > 1 {
			sw = fmt.Sprintf(" stroke-width=\"%d\"", bx.width)
		}
		fmt.Fprintf(b, "<polygon fill=\"%s\" stroke=\"%s\"%s points=\"%s,%s %s,%s %s,%s %s,%s %s,%s\"/>\n", fill, stroke, sw,
			svgNumber(bx.x0), y(bx.y0), svgNumber(bx.x0), y(bx.y1), svgNumber(bx.x1), y(bx.y1), svgNumber(bx.x1), y(bx.y0), svgNumber(bx.x0), y(bx.y0))
	}
}

// tableBox is a polygon of a table label, from (x0, y0) to (x1, y1): a fill
// without a stroke, or a border of stroke color and of a width.
type tableBox struct {
	fill, stroke   string
	width          int
	x0, y0, x1, y1 float64
}

// tableBoxes returns the polygons of a table label centered on c, as the
// reference draws them: a polygon filled with the table's background color
// and the table's border, then, for each cell, its fill and its border. A
// border is in the cell's color, the table's, or else pen, the color of the
// object's outline; one of 0 is not drawn, and one wider than 1 point lies
// half its width inside its box.
func tableBoxes(t layout.Text, c layout.Point, pen string) []tableBox {
	var out []tableBox
	border := func(color string, width int, x0, y0, x1, y1 float64) {
		if width == 0 {
			return
		}
		if width > 1 {
			// Rounded on its own, so that it is not fused into a
			// multiply-add.
			in := float64(float64(width) / 2)
			x0, y0, x1, y1 = x0+in, y0+in, x1-in, y1-in
		}
		out = append(out, tableBox{stroke: color, width: width, x0: x0, y0: y0, x1: x1, y1: y1})
	}
	tb := t.Table
	// Halves held apart from the sums, so that they are not fused into a
	// multiply-add.
	hw, hh := float64(t.Width/2), float64(t.Height/2)
	x0, x1 := c.X-hw, c.X+hw
	y0, y1 := c.Y-hh, c.Y+hh
	color := pen
	if tb.Color != "" {
		color = svgColor(tb.Color)
	}
	if tb.BgColor != "" {
		out = append(out, tableBox{fill: svgColor(tb.BgColor), x0: x0, y0: y0, x1: x1, y1: y1})
	}
	border(color, tb.Border, x0, y0, x1, y1)
	for _, row := range tb.Rows {
		for _, cell := range row {
			cx0, cy1 := x0+cell.Box.X, y1-cell.Box.Y
			cx1, cy0 := cx0+cell.Box.W, cy1-cell.Box.H
			if cell.BgColor != "" {
				out = append(out, tableBox{fill: svgColor(cell.BgColor), x0: cx0, y0: cy0, x1: cx1, y1: cy1})
			}
			cc := color
			if cell.Color != "" {
				cc = svgColor(cell.Color)
			}
			border(cc, cell.Border, cx0, cy0, cx1, cy1)
		}
	}
	return out
}

// textLine is a line of a label as it is drawn: its text and justification,
// x where it is anchored, and its baseline.
type textLine struct {
	text    string
	just    label.Justification
	x, base float64
}

// textLines returns the lines of a label centered on c that have text: each
// on its own baseline, 0.3 times the font size below the middle of its line,
// anchored at c or at the side of the label it is justified to.
func textLines(t layout.Text, c layout.Point) []textLine {
	var out []textLine
	n := len(t.Lines)
	lineHeight := float64(t.FontSize * 1.2)
	for i, l := range t.Lines {
		if l.Text == "" {
			continue
		}
		base := c.Y + float64(float64(float64(n-1)/2)*lineHeight) - float64(float64(i)*lineHeight) - float64(0.3*t.FontSize)
		x := c.X
		switch l.Just {
		case label.Left:
			x = c.X - float64(t.Width/2)
		case label.Right:
			x = c.X + float64(t.Width/2)
		}
		out = append(out, textLine{text: l.Text, just: l.Just, x: x, base: base})
	}
	return out
}

// writeText writes the lines of a label centered on c, as textLines places
// them.
func writeText(b *bytes.Buffer, t layout.Text, c layout.Point) {
	for _, l := range textLines(t, c) {
		anchor := "middle"
		switch l.just {
		case label.Left:
			anchor = "start"
		case label.Right:
			anchor = "end"
		}
		fill := ""
		if fc := svgColor(t.FontColor); fc != "black" && fc != "" {
			fill = ` fill="` + fc + `"`
		}
		fmt.Fprintf(b, "<text xml:space=\"preserve\" text-anchor=\"%s\" x=\"%s\" y=\"%s\"%s font-size=\"%.2f\"%s>%s</text>\n",
			anchor, svgNumber(l.x), y(l.base), fontAttrs(t.FontName), t.FontSize, fill, xmlText(l.text))
	}
}

func writeEdge(b *bytes.Buffer, e *layout.EdgeResult, id int, g *graph.Graph) {
	op := "--"
	if g.Directed() {
		op = "->"
	}
	// The title names the ports as they are written; the comment does not.
	end := func(n *graph.Node, attr string) string {
		if v, _ := e.Edge.Attr(g, attr); v.S != "" {
			return n.Name + ":" + v.S
		}
		return n.Name
	}
	name := xmlText(e.Edge.Tail.Name + op + e.Edge.Head.Name)
	title := xmlText(end(e.Edge.Tail, "tailport") + op + end(e.Edge.Head, "headport"))
	fmt.Fprintf(b, "<!-- %s -->\n<g id=\"edge%d\" class=\"edge\">\n<title>%s</title>\n", name, id, title)
	color := svgColor(e.Color)
	if len(e.Points) > 0 {
		var d strings.Builder
		for i, p := range e.Points {
			switch i {
			case 0:
				d.WriteString("M")
			case 1:
				d.WriteString("C")
			default:
				d.WriteString(" ")
			}
			d.WriteString(svgNumber(p.X) + "," + y(p.Y))
		}
		fmt.Fprintf(b, "<path fill=\"none\" stroke=\"%s\" d=\"%s\"/>\n", color, d.String())
	}
	for _, a := range []layout.Arrow{e.Tail, e.Head} {
		if a.Shape == "" {
			continue
		}
		pts := layout.ArrowPolygon(a)
		var s []string
		for _, p := range append(pts, pts[0]) {
			s = append(s, svgNumber(p.X)+","+y(p.Y))
		}
		fill := color
		if a.Shape == "empty" {
			fill = "none"
		}
		fmt.Fprintf(b, "<polygon fill=\"%s\" stroke=\"%s\" points=\"%s\"/>\n", fill, color, strings.Join(s, " "))
	}
	for _, l := range []struct {
		t layout.Text
		c layout.Point
	}{{e.Label, e.LabelPos}, {e.XLabel, e.XLabelPos}, {e.HeadLabel, e.HeadLabelPos}, {e.TailLabel, e.TailLabelPos}} {
		if l.t.Present() {
			writeLabel(b, l.t, l.c, color)
		}
	}
	b.WriteString("</g>\n")
}

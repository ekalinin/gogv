// Command fontmetrics generates the advance-width tables of internal/textmetrics
// from the Liberation 2.1.5 fonts (SIL Open Font License 1.1).
//
// It downloads the font archive by checksum into .cache/fonts, unpacks the
// twelve TrueType files into .cache/fonts/liberation (where the conformance
// harness also finds them for rasterizing), reads the advance width of every
// character of a fixed set of ranges, and writes them as Go tables. Only the
// tables are committed, never the fonts.
//
// Run it with go generate in internal/textmetrics.
package main

import (
	"archive/tar"
	"bytes"
	"compress/gzip"
	"crypto/sha256"
	"encoding/binary"
	"encoding/hex"
	"errors"
	"flag"
	"fmt"
	"go/format"
	"io"
	"net/http"
	"os"
	"path"
	"path/filepath"
	"strings"
)

const (
	archiveURL  = "https://github.com/liberationfonts/liberation-fonts/files/7261482/liberation-fonts-ttf-2.1.5.tar.gz"
	archiveSHA  = "7191c669bf38899f73a2094ed00f7b800553364f90e2637010a69c0e268f25d0"
	archiveName = "liberation-fonts-ttf-2.1.5.tar.gz"
)

// Faces, in the order of the generated table: family, then style.
var faces = []string{
	"LiberationSerif-Regular", "LiberationSerif-Bold", "LiberationSerif-Italic", "LiberationSerif-BoldItalic",
	"LiberationSans-Regular", "LiberationSans-Bold", "LiberationSans-Italic", "LiberationSans-BoldItalic",
	"LiberationMono-Regular", "LiberationMono-Bold", "LiberationMono-Italic", "LiberationMono-BoldItalic",
}

// Ranges of characters whose widths are tabulated: the printable characters
// of Basic Latin. The reference measures every byte of a non-ASCII character
// as a space, so wider tables would only move gogv away from it.
var ranges = [][2]rune{
	{0x20, 0x7e},
}

func main() {
	out := flag.String("out", "tables.go", "generated Go file")
	flag.Parse()

	root, err := repoRoot()
	if err != nil {
		fail(err)
	}
	dir := filepath.Join(root, ".cache", "fonts", "liberation")
	if err := fetch(filepath.Join(root, ".cache", "fonts"), dir); err != nil {
		fail(err)
	}
	var b bytes.Buffer
	b.WriteString(`// SPDX-License-Identifier: MIT
// Provenance: liberation-fonts 2.1.5

// Code generated by tools/fontmetrics from the Liberation 2.1.5 fonts; DO NOT EDIT.

package textmetrics

// faceTables holds, for each face of the faces table, the advance widths of
// the tabulated characters in font units. A zero width marks a character the
// font has no glyph for.
var faceTables = [...]faceTable{
`)
	for _, name := range faces {
		data, err := os.ReadFile(filepath.Join(dir, name+".ttf"))
		if err != nil {
			fail(err)
		}
		f, err := parseFont(data)
		if err != nil {
			fail(fmt.Errorf("%s: %w", name, err))
		}
		fmt.Fprintf(&b, "\t{name: %q, unitsPerEm: %d, ranges: []widthRange{\n", name, f.unitsPerEm)
		for _, r := range ranges {
			fmt.Fprintf(&b, "\t\t{first: %#x, widths: []uint16{", r[0])
			for c := r[0]; c <= r[1]; c++ {
				if (c-r[0])%16 == 0 {
					b.WriteString("\n\t\t\t")
				}
				fmt.Fprintf(&b, "%d, ", f.advance(c))
			}
			b.WriteString("\n\t\t}},\n")
		}
		b.WriteString("\t}},\n")
	}
	b.WriteString("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		fail(err)
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		fail(err)
	}
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "fontmetrics:", err)
	os.Exit(1)
}

// repoRoot returns the directory of go.mod, searching upward from the
// working directory.
func repoRoot() (string, error) {
	dir, err := os.Getwd()
	if err != nil {
		return "", err
	}
	for {
		if _, err := os.Stat(filepath.Join(dir, "go.mod")); err == nil {
			return dir, nil
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return "", errors.New("go.mod not found")
		}
		dir = parent
	}
}

// fetch downloads the archive into cache when it is missing, checks its
// checksum, and unpacks the TrueType files and the license into dir.
func fetch(cache, dir string) error {
	archive := filepath.Join(cache, archiveName)
	data, err := os.ReadFile(archive)
	if err != nil {
		resp, err := http.Get(archiveURL)
		if err != nil {
			return err
		}
		defer resp.Body.Close()
		if resp.StatusCode != http.StatusOK {
			return fmt.Errorf("download %s: %s", archiveURL, resp.Status)
		}
		if data, err = io.ReadAll(resp.Body); err != nil {
			return err
		}
	}
	sum := sha256.Sum256(data)
	if hex.EncodeToString(sum[:]) != archiveSHA {
		return fmt.Errorf("%s: checksum mismatch", archiveName)
	}
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	if err := os.WriteFile(archive, data, 0o644); err != nil {
		return err
	}
	zr, err := gzip.NewReader(bytes.NewReader(data))
	if err != nil {
		return err
	}
	tr := tar.NewReader(zr)
	for {
		h, err := tr.Next()
		if err == io.EOF {
			return nil
		}
		if err != nil {
			return err
		}
		name := path.Base(h.Name)
		if h.Typeflag != tar.TypeReg || (!strings.HasSuffix(name, ".ttf") && name != "LICENSE") {
			continue
		}
		body, err := io.ReadAll(tr)
		if err != nil {
			return err
		}
		if err := os.WriteFile(filepath.Join(dir, name), body, 0o644); err != nil {
			return err
		}
	}
}

// font is what the generator reads from a TrueType file.
type font struct {
	unitsPerEm uint16
	advances   []uint16       // by glyph, from hmtx
	glyphs     map[rune]int32 // from cmap
}

func (f font) advance(c rune) uint16 {
	g, ok := f.glyphs[c]
	if !ok || g == 0 {
		return 0
	}
	if int(g) >= len(f.advances) {
		return f.advances[len(f.advances)-1]
	}
	return f.advances[g]
}

// parseFont reads the head, hhea, hmtx and cmap tables.
func parseFont(data []byte) (font, error) {
	be := binary.BigEndian
	if len(data) < 12 {
		return font{}, errors.New("short file")
	}
	tables := map[string][]byte{}
	n := int(be.Uint16(data[4:]))
	for i := range n {
		rec := 12 + 16*i
		if rec+16 > len(data) {
			return font{}, errors.New("short table directory")
		}
		tag := string(data[rec : rec+4])
		off, length := be.Uint32(data[rec+8:]), be.Uint32(data[rec+12:])
		if uint64(off)+uint64(length) > uint64(len(data)) {
			return font{}, fmt.Errorf("table %s out of range", tag)
		}
		tables[tag] = data[off : off+length]
	}
	head, hhea, hmtx, cmap := tables["head"], tables["hhea"], tables["hmtx"], tables["cmap"]
	if len(head) < 54 || len(hhea) < 36 || hmtx == nil || cmap == nil {
		return font{}, errors.New("missing head, hhea, hmtx or cmap")
	}
	f := font{unitsPerEm: be.Uint16(head[18:]), glyphs: map[rune]int32{}}
	numH := int(be.Uint16(hhea[34:]))
	if len(hmtx) < 4*numH {
		return font{}, errors.New("short hmtx")
	}
	for i := range numH {
		f.advances = append(f.advances, be.Uint16(hmtx[4*i:]))
	}

	// Prefer the full Unicode subtable (3, 10, format 12), then the BMP one
	// (3, 1, format 4).
	var sub4, sub12 []byte
	for i := range int(be.Uint16(cmap[2:])) {
		rec := 4 + 8*i
		platform, encoding, off := be.Uint16(cmap[rec:]), be.Uint16(cmap[rec+2:]), be.Uint32(cmap[rec+4:])
		if int(off) >= len(cmap) || platform != 3 {
			continue
		}
		switch format := be.Uint16(cmap[off:]); {
		case encoding == 10 && format == 12:
			sub12 = cmap[off:]
		case encoding == 1 && format == 4:
			sub4 = cmap[off:]
		}
	}
	switch {
	case sub12 != nil:
		groups := int(be.Uint32(sub12[12:]))
		for i := range groups {
			g := sub12[16+12*i:]
			start, end, glyph := be.Uint32(g), be.Uint32(g[4:]), be.Uint32(g[8:])
			for c := start; c <= end; c++ {
				f.glyphs[rune(c)] = int32(glyph + c - start)
			}
		}
	case sub4 != nil:
		segX2 := int(be.Uint16(sub4[6:]))
		ends, starts, deltas, offsets := 14, 16+segX2, 16+2*segX2, 16+3*segX2
		for s := 0; s < segX2; s += 2 {
			end, start := be.Uint16(sub4[ends+s:]), be.Uint16(sub4[starts+s:])
			delta, rangeOff := be.Uint16(sub4[deltas+s:]), be.Uint16(sub4[offsets+s:])
			for c := uint32(start); c <= uint32(end) && c != 0xffff; c++ {
				var g uint16
				if rangeOff == 0 {
					g = uint16(c) + delta
				} else {
					at := offsets + s + int(rangeOff) + 2*int(c-uint32(start))
					if at+2 > len(sub4) {
						continue
					}
					if g = be.Uint16(sub4[at:]); g != 0 {
						g += delta
					}
				}
				f.glyphs[rune(c)] = int32(g)
			}
		}
	default:
		return font{}, errors.New("no Unicode cmap subtable")
	}
	return f, nil
}

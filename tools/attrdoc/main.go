// Command attrdoc generates internal/attrs/documented.go, the list of the
// attributes that the Graphviz documentation describes, with the kinds of
// objects that use them, from the attribute table of
// https://graphviz.org/doc/info/attrs.html.
//
// Run it with go generate in internal/attrs.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"io"
	"net/http"
	"os"
	"regexp"
	"slices"
	"strings"
)

const pageURL = "https://graphviz.org/doc/info/attrs.html"

var (
	rowRE  = regexp.MustCompile(`(?is)<TR>(.*?)</TR>`)
	cellRE = regexp.MustCompile(`(?is)<TD[^>]*>(.*?)</TD>`)
	tagRE  = regexp.MustCompile(`<[^>]+>`)
	nameRE = regexp.MustCompile(`^[A-Za-z_]+$`)
)

func main() {
	out := flag.String("out", "documented.go", "generated Go file")
	page := flag.String("page", "", "saved copy of the attribute page (downloaded when empty)")
	flag.Parse()
	if err := run(*out, *page); err != nil {
		fmt.Fprintln(os.Stderr, "attrdoc:", err)
		os.Exit(1)
	}
}

func run(out, page string) error {
	var data []byte
	var err error
	if page != "" {
		data, err = os.ReadFile(page)
	} else {
		data, err = download()
	}
	if err != nil {
		return err
	}
	type entry struct {
		name  string
		flags []string
	}
	var entries []entry
	for _, row := range rowRE.FindAllSubmatch(data, -1) {
		cells := cellRE.FindAllSubmatch(row[1], -1)
		if len(cells) < 2 {
			continue
		}
		name := strings.TrimSpace(tagRE.ReplaceAllString(string(cells[0][1]), ""))
		used := strings.TrimSpace(tagRE.ReplaceAllString(string(cells[1][1]), ""))
		if !nameRE.MatchString(name) {
			continue
		}
		var flags []string
		for u := range strings.SplitSeq(used, ",") {
			switch strings.TrimSpace(u) {
			case "Graphs":
				flags = append(flags, "UsedByGraphs")
			case "Subgraphs":
				flags = append(flags, "UsedBySubgraphs")
			case "Clusters":
				flags = append(flags, "UsedByClusters")
			case "Nodes":
				flags = append(flags, "UsedByNodes")
			case "Edges":
				flags = append(flags, "UsedByEdges")
			default:
				return fmt.Errorf("attribute %s: unknown user %q", name, u)
			}
		}
		entries = append(entries, entry{name, flags})
	}
	if len(entries) < 100 {
		return fmt.Errorf("only %d attributes found: the page layout changed", len(entries))
	}
	slices.SortFunc(entries, func(a, b entry) int { return strings.Compare(a.name, b.name) })

	var b bytes.Buffer
	b.WriteString(`// SPDX-License-Identifier: MIT
// Provenance: doc https://graphviz.org/doc/info/attrs.html

// Code generated by tools/attrdoc from the Graphviz attribute documentation; DO NOT EDIT.

package attrs

// documented maps every attribute that the Graphviz documentation describes
// to the kinds of objects that use it.
var documented = map[string]UsedBy{
`)
	for _, e := range entries {
		fmt.Fprintf(&b, "\t%q: %s,\n", e.name, strings.Join(e.flags, " | "))
	}
	b.WriteString("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		return err
	}
	return os.WriteFile(out, src, 0o644)
}

func download() ([]byte, error) {
	resp, err := http.Get(pageURL)
	if err != nil {
		return nil, err
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("download %s: %s", pageURL, resp.Status)
	}
	return io.ReadAll(resp.Body)
}
